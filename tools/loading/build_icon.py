#!/usr/bin/env python3
"""Build-time loading icon (phase 5b): sonic-spinning.gif -> ps1/loading_icon.h.

The GIF (48x48, 8 frames, 15 colours + transparent) becomes one 4-bit texture page slice:
frames 0-4 side by side on the first 48 rows, frames 5-7 on the next 48 (256x96 texels =
64x96 halfwords, texel 0 in bits 0-3), plus a 16-entry 15-bit CLUT (index 0 = transparent =
0x0000; visible black -> 0x8000). Compiled into the executable: during a load the disc is busy,
so the icon can't be read from it. Every frame is decoded back and compared with the GIF.

Usage: build_icon.py [GIF] [OUT_HEADER]   (defaults: ../sonic-spinning.gif, ps1/loading_icon.h)
"""
import os, sys
from PIL import Image, ImageSequence

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
FW = FH = 48
PER_ROW = 5
TEX_W, TEX_H = 256, 96  # texels


def conv(rgb):
    r, g, b = rgb
    v = (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)
    return v if v else 0x8000


def main():
    gif = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, '..', 'sonic-spinning.gif')
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(REPO, 'ps1', 'loading_icon.h')
    im = Image.open(gif)
    frames = [f.convert('RGBA') for f in ImageSequence.Iterator(im)]
    durations = [f.info.get('duration', 20) for f in ImageSequence.Iterator(Image.open(gif))]
    assert all(f.size == (FW, FH) for f in frames), 'frames must be 48x48'
    colours = []
    for f in frames:
        for px in f.getdata():
            if px[3] >= 128 and px[:3] not in colours:
                colours.append(px[:3])
    if len(colours) > 15:
        sys.exit('ERROR: %d colours > 15 (4-bit CLUT)' % len(colours))
    index = {c: i + 1 for i, c in enumerate(colours)}
    clut = [0x0000] + [conv(c) for c in colours] + [0x0000] * (15 - len(colours))
    tex = [[0] * TEX_W for _ in range(TEX_H)]
    for n, f in enumerate(frames):
        ox, oy = (n % PER_ROW) * FW, (n // PER_ROW) * FH
        px = f.load()
        for y in range(FH):
            for x in range(FW):
                p = px[x, y]
                tex[oy + y][ox + x] = index[p[:3]] if p[3] >= 128 else 0
    words = []
    for y in range(TEX_H):
        for x in range(0, TEX_W, 4):
            t = tex[y][x:x + 4]
            words.append(t[0] | (t[1] << 4) | (t[2] << 8) | (t[3] << 12))
    # Self-check: decode the packed texture back through the CLUT and compare with the GIF.
    for n, f in enumerate(frames):
        ox, oy = (n % PER_ROW) * FW, (n // PER_ROW) * FH
        px = f.load()
        for y in range(FH):
            for x in range(FW):
                w = words[(oy + y) * (TEX_W // 4) + (ox + x) // 4]
                i = (w >> (((ox + x) & 3) * 4)) & 0xF
                p = px[x, y]
                want = conv(p[:3]) if p[3] >= 128 else 0x0000
                assert clut[i] == want, 'frame %d (%d,%d): %04x != %04x' % (n, x, y, clut[i], want)
    lines = ['// Generated by tools/loading/build_icon.py from sonic-spinning.gif -- do not edit.',
             '// 4-bit texture: 8 frames of 48x48 (5 + 3 per 48-row band), 256x96 texels = 64x96 halfwords.',
             '#pragma once', '#include <stdint.h>', '',
             '#define PS1_LOADING_ICON_FRAMES   %d' % len(frames),
             '#define PS1_LOADING_ICON_SIZE     %d' % FW,
             '#define PS1_LOADING_ICON_PER_ROW  %d' % PER_ROW,
             '#define PS1_LOADING_ICON_TEX_HW   %d // texture width in halfwords' % (TEX_W // 4),
             '#define PS1_LOADING_ICON_TEX_H    %d' % TEX_H,
             '#define PS1_LOADING_ICON_FRAME_US %d // GIF frame duration' % (durations[0] * 1000), '',
             'alignas(4) static const uint16_t s_ps1LoadingIconClut[16] = {']
    lines.append('    ' + ', '.join('0x%04x' % v for v in clut) + ',')
    lines.append('};')
    lines.append('alignas(4) static const uint16_t s_ps1LoadingIconTex[%d] = {' % len(words))
    for i in range(0, len(words), 16):
        lines.append('    ' + ', '.join('0x%04x' % v for v in words[i:i + 16]) + ',')
    lines.append('};')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print('%s: %d frames %dx%d, %d colours + transparent, texture %d B, self-check exact' % (
        os.path.relpath(out, REPO), len(frames), FW, FH, len(colours), len(words) * 2))


if __name__ == '__main__':
    main()
